"""Regenerate ml/test_vectors.json (run from the repo root: .venv/bin/python -m ml.make_test_vectors).

The file holds 5 puzzles from web/data/puzzles.json with their expected features, so the
TypeScript implementation (web/lib/predict.ts) can be checked against Python within 1e-6.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

from ml.features import CELL_FEATURES, PUZZLE_FEATURES, cell_features, load_puzzles, puzzle_features

OUT = Path(__file__).resolve().parent / "test_vectors.json"
N_VECTORS = 5

COMMENT = (
    "Expected features and predictions for 5 puzzles from web/data/puzzles.json. Generated by "
    "ml/make_test_vectors.py; do not edit by hand. The TypeScript side must match every number here "
    "within 1e-6. `cells` follows solution order, and each cell lists features in the order of "
    "`cell_features`. `parity_model` is a SYNTHETIC model made up only to exercise the math (time "
    "coefficients incl. solver_steps, a player offset, stuck coefficients). It is not trained on any "
    "data and is never exported to the app. `predictions` are computed from it: time_log, time_value "
    "= exp(time_log) with no player, time_value_with_player for player `parity-player`, stuck_scores "
    "in solution order, stuck_top3 = the 3 highest scores, ties broken by solution order."
)

PARITY_PLAYER = "parity-player"
PARITY_MODEL = {
    "version": "parity-fixture",
    "trained_on": {"human_solves": 0, "label": "human_time"},
    "puzzle_features": PUZZLE_FEATURES,
    "time": {
        "intercept": 7.5,
        "coef": {"grid_size": 0.3, "n_dots": 0.02, "max_gap": 0.05, "mean_gap": 0.4, "turns": 0.03, "solver_steps": 0.004},
        "residual_std": 0.5,
    },
    "players": {PARITY_PLAYER: 0.25},
    "cell_features": CELL_FEATURES,
    "stuck": {
        "intercept": -3.0,
        "coef": {"dist_to_next_dot": 0.4, "is_edge": 0.3, "is_corner": 0.5, "is_turn": 0.6, "segment_len": 0.1, "path_frac": -0.7},
    },
}


def predictions(model: dict[str, object], pf: dict[str, float], cells: list[dict[str, object]]) -> dict[str, object]:
    """Reference predictions straight from the contract formulas in CLAUDE.md."""
    t = model["time"]
    z = t["intercept"] + sum(t["coef"][f] * pf[f] for f in PUZZLE_FEATURES)
    s = model["stuck"]
    scores = [s["intercept"] + sum(s["coef"][f] * c["features"][f] for f in CELL_FEATURES) for c in cells]
    order = sorted(range(len(scores)), key=lambda i: (-scores[i], i))
    return {
        "time_log": z,
        "time_value": math.exp(z),
        "time_value_with_player": math.exp(z + model["players"][PARITY_PLAYER]),
        "stuck_scores": scores,
        "stuck_top3": [cells[i]["cell"] for i in order[:3]],
    }


def build() -> dict[str, object]:
    puzzles = load_puzzles()
    step = len(puzzles) // N_VECTORS  # spread picks across the file (mix of grid sizes)
    chosen = puzzles[::step][:N_VECTORS]
    vectors = []
    for p in chosen:
        feats = cell_features(p)
        pf = puzzle_features(p)
        cells = [{"cell": [r, c], "features": feats[(r, c)]} for r, c in p["solution"]]
        vectors.append({
            "id": p["id"],
            "n": p["n"],
            "dots": p["dots"],
            "solution": p["solution"],
            "puzzle_features": pf,
            "cells": cells,
            "predictions": predictions(PARITY_MODEL, pf, cells),
        })
    return {
        "_comment": COMMENT,
        "puzzle_features": PUZZLE_FEATURES,
        "cell_features": CELL_FEATURES,
        "parity_model": PARITY_MODEL,
        "vectors": vectors,
    }


if __name__ == "__main__":
    OUT.write_text(json.dumps(build(), indent=1) + "\n")
    print(f"wrote {OUT}")
