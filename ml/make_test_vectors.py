"""Regenerate ml/test_vectors.json (run from the repo root: .venv/bin/python -m ml.make_test_vectors).

The file holds 5 puzzles from web/data/puzzles.json with their expected features, so the
TypeScript implementation (web/lib/predict.ts) can be checked against Python within 1e-6.
"""
from __future__ import annotations

import json
from pathlib import Path

from ml.features import CELL_FEATURES, PUZZLE_FEATURES, cell_features, load_puzzles, puzzle_features

OUT = Path(__file__).resolve().parent / "test_vectors.json"
N_VECTORS = 5

COMMENT = (
    "Expected features for 5 puzzles from web/data/puzzles.json. Generated by ml/make_test_vectors.py; "
    "do not edit by hand. Predictions (time and stuck score) are NOT included yet: they need the trained "
    "models from Sprint 2 task 4 and 5, and will be added then. The TypeScript side must match every "
    "number here within 1e-6. `cells` follows solution order, and each cell lists features in the order "
    "of `cell_features`."
)


def build() -> dict[str, object]:
    puzzles = load_puzzles()
    step = len(puzzles) // N_VECTORS  # spread picks across the file (mix of grid sizes)
    chosen = puzzles[::step][:N_VECTORS]
    vectors = []
    for p in chosen:
        feats = cell_features(p)
        vectors.append({
            "id": p["id"],
            "n": p["n"],
            "dots": p["dots"],
            "solution": p["solution"],
            "puzzle_features": puzzle_features(p),
            "cells": [{"cell": [r, c], "features": feats[(r, c)]} for r, c in p["solution"]],
        })
    return {
        "_comment": COMMENT,
        "puzzle_features": PUZZLE_FEATURES,
        "cell_features": CELL_FEATURES,
        "vectors": vectors,
    }


if __name__ == "__main__":
    OUT.write_text(json.dumps(build(), indent=1) + "\n")
    print(f"wrote {OUT}")
