"""Regenerate ml/test_vectors.json (run from the repo root: .venv/bin/python -m ml.make_test_vectors).

The file holds 5 puzzles from web/data/puzzles.json with their expected features, so the
TypeScript implementation (web/lib/predict.ts) can be checked against Python within 1e-6.
"""
from __future__ import annotations

import json
from pathlib import Path

from ml.features import CELL_FEATURES, PUZZLE_FEATURES, cell_features, load_puzzles, puzzle_features
from ml.predict import log_time, predict_time, stuck_scores, stuck_top

OUT = Path(__file__).resolve().parent / "test_vectors.json"
N_VECTORS = 5

COMMENT = (
    "Expected features and predictions for 5 puzzles from web/data/puzzles.json. Generated by "
    "ml/make_test_vectors.py; do not edit by hand. Predictions use the fixed `model` below (hand-set, "
    "not trained, so retraining never changes this file) through ml/predict.py. The TypeScript side "
    "(web/lib/predict.ts) must match every number here within 1e-6. `cells` follows solution order, and "
    "each cell lists features in the order of `cell_features`; `stuck.scores` follows the same order."
)

PLAYER = "00000000-0000-4000-8000-000000000001"

# Hand-set model in the model.json contract shape. Every coefficient is non-zero so each feature is exercised.
MODEL = {
    "version": "test-vectors",
    "trained_on": {"human_solves": 0, "label": "human_time"},
    "puzzle_features": PUZZLE_FEATURES,
    "time": {
        "intercept": 7.5,
        "coef": {"grid_size": 0.3, "n_dots": -0.02, "max_gap": 0.05, "mean_gap": 0.1, "turns": 0.01,
                 "solver_steps": 0.0001},
        "residual_std": 0.5,
    },
    "players": {PLAYER: 0.2},
    "cell_features": CELL_FEATURES,
    "stuck": {
        "intercept": -3.0,
        "coef": {"dist_to_next_dot": 0.15, "is_edge": -0.2, "is_corner": 0.3, "is_turn": 0.4,
                 "segment_len": 0.05, "path_frac": -0.5},
    },
}


def build() -> dict[str, object]:
    puzzles = load_puzzles()
    step = len(puzzles) // N_VECTORS  # spread picks across the file (mix of grid sizes)
    chosen = puzzles[::step][:N_VECTORS]
    vectors = []
    for p in chosen:
        feats = cell_features(p)
        vectors.append({
            "id": p["id"],
            "n": p["n"],
            "dots": p["dots"],
            "solution": p["solution"],
            "puzzle_features": puzzle_features(p),
            "cells": [{"cell": [r, c], "features": feats[(r, c)]} for r, c in p["solution"]],
            "time": {
                "log_value": log_time(MODEL, p),
                "value": predict_time(MODEL, p),
                "value_for_player": predict_time(MODEL, p, PLAYER),
            },
            "stuck": {
                "scores": [score for _, score in stuck_scores(MODEL, p)],
                "top3": [list(cell) for cell in stuck_top(MODEL, p)],
            },
        })
    return {
        "_comment": COMMENT,
        "puzzle_features": PUZZLE_FEATURES,
        "cell_features": CELL_FEATURES,
        "player_id": PLAYER,
        "model": MODEL,
        "vectors": vectors,
    }


if __name__ == "__main__":
    OUT.write_text(json.dumps(build(), indent=1) + "\n")
    print(f"wrote {OUT}")
